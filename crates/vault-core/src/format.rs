//! On-disk structures and the outer file layout (sections 2 and 3).

use serde::{Deserialize, Serialize};

use crate::Error;
use crate::crypto::NONCE_LEN;

/// File magic, section 2.
pub const MAGIC: [u8; 8] = *b"SVAULT\x00\x01";
/// The only format version this crate reads and writes.
pub const FORMAT_VERSION: u16 = 1;
/// XChaCha20-Poly1305, the only AEAD in format version 1.
pub(crate) const AEAD_XCHACHA20POLY1305: u8 = 1;

pub(crate) const PREFIX_LEN: usize = 8 + 2 + 4;
pub(crate) const MAX_HEADER_LEN: usize = 1 << 20;
pub(crate) const MAX_SLOTS: usize = 32;
const MAX_CREDENTIAL_ID: usize = 1023;
const MAX_RP_ID: usize = 253;
const MAX_TPM_BLOB: usize = 4096;
const MAX_PCRS: usize = 24;

/// Random 16-byte keyslot identifier.
pub type SlotId = [u8; 16];

#[derive(Serialize, Deserialize)]
pub(crate) struct Header {
    pub vault_id: [u8; 16],
    pub aead: u8,
    pub slots: Vec<Keyslot>,
}

#[derive(Serialize, Deserialize, Clone)]
pub(crate) struct Keyslot {
    pub meta: KeyslotMeta,
    pub nonce: [u8; NONCE_LEN],
    pub commit: [u8; 32],
    #[serde(with = "arr48")]
    pub wrapped_vault_key: [u8; 48],
}

/// The public part of a keyslot: everything that decides how its KEK is
/// derived. All of it is bound into the slot's AAD (section 4.3).
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
pub struct KeyslotMeta {
    /// Random slot identifier.
    pub id: SlotId,
    /// Argon2id parameters; `None` only for [`Factor::Recovery`].
    pub kdf: Option<Argon2Params>,
    /// HKDF salt for the KEK.
    pub salt: [u8; 32],
    /// What unlocks this slot.
    pub factor: Factor,
}

/// Argon2id parameters stored per slot. The Argon2 version is always 0x13.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
pub struct Argon2Params {
    /// Memory in KiB.
    pub m_kib: u32,
    /// Iterations.
    pub t: u32,
    /// Lanes.
    pub p: u32,
    /// Argon2 salt.
    pub salt: [u8; 32],
}

/// Argon2id cost chosen by the caller when enrolling a slot; salts are
/// generated by this crate.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct KdfCost {
    /// Memory in KiB.
    pub m_kib: u32,
    /// Iterations.
    pub t: u32,
    /// Lanes.
    pub p: u32,
}

impl KdfCost {
    /// Writer default from section 3.1, before calibration: 256 MiB, t = 3, p = 4.
    pub const DEFAULT: KdfCost = KdfCost {
        m_kib: 262_144,
        t: 3,
        p: 4,
    };
    /// The smallest cost the format accepts. For tests only.
    pub const MINIMUM: KdfCost = KdfCost {
        m_kib: 65_536,
        t: 1,
        p: 1,
    };
}

impl Argon2Params {
    /// Section 3.1 bounds, checked before any KDF runs.
    pub(crate) fn check_bounds(&self) -> Result<(), Error> {
        let ok = (65_536..=4_194_304).contains(&self.m_kib)
            && (1..=20).contains(&self.t)
            && (1..=16).contains(&self.p);
        if ok {
            Ok(())
        } else {
            Err(Error::KdfOutOfBounds)
        }
    }
}

/// The factor that unlocks a keyslot (section 3).
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
pub enum Factor {
    /// Password alone.
    PasswordOnly,
    /// Password plus a FIDO2 security key's hmac-secret output.
    PasswordFido2 {
        /// Credential ID on the security key.
        credential_id: Vec<u8>,
        /// Relying party ID; fixed for the life of the slot.
        rp_id: String,
        /// Random PRF input; the hmac-secret salt is derived from it (section 4.2).
        prf_input: [u8; 32],
        /// Whether user verification (PIN) is performed. The authenticator
        /// returns a different secret with and without UV.
        require_uv: bool,
    },
    /// Password plus a TPM-sealed secret.
    PasswordTpm {
        /// Marshalled TPM2B_PUBLIC || TPM2B_PRIVATE.
        blob: Vec<u8>,
        /// Optional PCR policy.
        pcr_policy: Option<PcrPolicy>,
        /// Whether the sealed object has an authValue (PIN).
        has_pin: bool,
    },
    /// 256-bit recovery secret, unlocks alone.
    Recovery,
    /// Reserved for a later format version.
    PasswordPasskeyPrf,
    /// Reserved for a later format version.
    PasswordDevice,
    /// Reserved for a later format version.
    PasswordPhone,
    /// Reserved for a later format version.
    RecipientHybrid,
}

/// TPM PCR policy for a [`Factor::PasswordTpm`] slot.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
pub struct PcrPolicy {
    /// PCR bank; 1 = SHA-256.
    pub bank: u8,
    /// PCR indices, e.g. `[7]`.
    pub pcrs: Vec<u8>,
}

impl Factor {
    /// Daily-use factors always include the password.
    pub fn is_daily_use(&self) -> bool {
        matches!(
            self,
            Factor::PasswordOnly | Factor::PasswordFido2 { .. } | Factor::PasswordTpm { .. }
        )
    }

    /// Whether a v1 reader can unlock this kind of slot.
    pub fn is_supported(&self) -> bool {
        self.is_daily_use() || matches!(self, Factor::Recovery)
    }

    /// Whether the KEK mixes in a hardware secret.
    pub(crate) fn needs_hw_key(&self) -> bool {
        matches!(
            self,
            Factor::PasswordFido2 { .. } | Factor::PasswordTpm { .. }
        )
    }

    fn check_lengths(&self) -> Result<(), Error> {
        let ok = match self {
            Factor::PasswordFido2 {
                credential_id,
                rp_id,
                ..
            } => credential_id.len() <= MAX_CREDENTIAL_ID && rp_id.len() <= MAX_RP_ID,
            Factor::PasswordTpm {
                blob, pcr_policy, ..
            } => {
                blob.len() <= MAX_TPM_BLOB
                    && pcr_policy.as_ref().is_none_or(|p| p.pcrs.len() <= MAX_PCRS)
            }
            _ => true,
        };
        if ok { Ok(()) } else { Err(Error::Malformed) }
    }
}

impl KeyslotMeta {
    pub(crate) fn validate(&self) -> Result<(), Error> {
        self.factor.check_lengths()?;
        match (&self.factor, &self.kdf) {
            (Factor::Recovery, None) => Ok(()),
            (Factor::Recovery, Some(_)) => Err(Error::Malformed),
            (f, None) if f.is_daily_use() => Err(Error::Malformed),
            _ => Ok(()),
        }
    }
}

pub(crate) fn encode<T: Serialize>(v: &T) -> Vec<u8> {
    postcard::to_allocvec(v).expect("serializing to a Vec cannot fail")
}

/// Decode `bytes` completely and require that re-encoding reproduces them, so
/// that every MAC and AAD computed over stored bytes matches the re-encoded
/// structure (section 1).
pub(crate) fn decode_canonical<'a, T: Serialize + Deserialize<'a>>(
    bytes: &'a [u8],
) -> Result<T, Error> {
    let (v, rest) = postcard::take_from_bytes::<T>(bytes).map_err(|_| Error::Malformed)?;
    if !rest.is_empty() {
        return Err(Error::Malformed);
    }
    if encode(&v) != bytes {
        return Err(Error::NonCanonical);
    }
    Ok(v)
}

/// A vault file split into its parts but not yet unlocked.
pub struct ParsedVault {
    pub(crate) header: Header,
    /// `bytes[0 .. 14 + header_len]`, the range the header MAC covers.
    pub(crate) mac_input: Vec<u8>,
    pub(crate) header_mac: [u8; 32],
    pub(crate) body: SealedBody,
}

#[derive(Serialize, Deserialize)]
pub(crate) struct SealedBody {
    pub nonce: [u8; NONCE_LEN],
    pub commit: [u8; 32],
    pub ciphertext: Vec<u8>,
}

impl ParsedVault {
    /// Parse a vault file (section 2). Performs no cryptography.
    pub fn parse(bytes: &[u8]) -> Result<ParsedVault, Error> {
        if bytes.len() < PREFIX_LEN || bytes[..8] != MAGIC {
            return Err(Error::Malformed);
        }
        let version = u16::from_le_bytes([bytes[8], bytes[9]]);
        if version != FORMAT_VERSION {
            return Err(Error::Unsupported);
        }
        let header_len = u32::from_le_bytes(bytes[10..14].try_into().unwrap()) as usize;
        if header_len > MAX_HEADER_LEN {
            return Err(Error::Malformed);
        }
        let header_end = PREFIX_LEN.checked_add(header_len).ok_or(Error::Malformed)?;
        let mac_end = header_end + 32;
        let body_start = mac_end + 8;
        if bytes.len() < body_start {
            return Err(Error::Malformed);
        }
        let body_len = u64::from_le_bytes(bytes[mac_end..body_start].try_into().unwrap());
        if body_len != (bytes.len() - body_start) as u64 {
            return Err(Error::Malformed);
        }

        let header: Header = decode_canonical(&bytes[PREFIX_LEN..header_end])?;
        if header.aead != AEAD_XCHACHA20POLY1305 {
            return Err(Error::Unsupported);
        }
        if header.slots.is_empty() || header.slots.len() > MAX_SLOTS {
            return Err(Error::Malformed);
        }
        for s in &header.slots {
            s.meta.validate()?;
        }
        let body: SealedBody = decode_canonical(&bytes[body_start..])?;

        Ok(ParsedVault {
            header,
            mac_input: bytes[..header_end].to_vec(),
            header_mac: bytes[header_end..mac_end].try_into().unwrap(),
            body,
        })
    }

    /// The vault's permanent identifier.
    pub fn vault_id(&self) -> [u8; 16] {
        self.header.vault_id
    }

    /// Public metadata of every keyslot, so the caller can decide which factor
    /// to collect (for example, which security key to ask for).
    pub fn slots(&self) -> impl Iterator<Item = &KeyslotMeta> {
        self.header.slots.iter().map(|s| &s.meta)
    }
}

/// Assemble the outer layout from encoded parts.
pub(crate) fn assemble(header_bytes: &[u8], header_mac: &[u8; 32], body_bytes: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(PREFIX_LEN + header_bytes.len() + 40 + body_bytes.len());
    out.extend_from_slice(&prefix(header_bytes.len()));
    out.extend_from_slice(header_bytes);
    out.extend_from_slice(header_mac);
    out.extend_from_slice(&(body_bytes.len() as u64).to_le_bytes());
    out.extend_from_slice(body_bytes);
    out
}

pub(crate) fn prefix(header_len: usize) -> [u8; PREFIX_LEN] {
    let mut p = [0u8; PREFIX_LEN];
    p[..8].copy_from_slice(&MAGIC);
    p[8..10].copy_from_slice(&FORMAT_VERSION.to_le_bytes());
    p[10..14].copy_from_slice(&(header_len as u32).to_le_bytes());
    p
}

/// serde supports fixed arrays only up to 32 elements; encode 48 as a tuple.
pub(crate) mod arr48 {
    use core::fmt;
    use serde::de::{self, SeqAccess, Visitor};
    use serde::ser::SerializeTuple;
    use serde::{Deserializer, Serializer};

    pub fn serialize<S: Serializer>(v: &[u8; 48], s: S) -> Result<S::Ok, S::Error> {
        let mut t = s.serialize_tuple(48)?;
        for b in v {
            t.serialize_element(b)?;
        }
        t.end()
    }

    pub fn deserialize<'de, D: Deserializer<'de>>(d: D) -> Result<[u8; 48], D::Error> {
        struct V;
        impl<'de> Visitor<'de> for V {
            type Value = [u8; 48];
            fn expecting(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                f.write_str("48 bytes")
            }
            fn visit_seq<A: SeqAccess<'de>>(self, mut a: A) -> Result<[u8; 48], A::Error> {
                let mut out = [0u8; 48];
                for (i, o) in out.iter_mut().enumerate() {
                    *o = a
                        .next_element()?
                        .ok_or_else(|| de::Error::invalid_length(i, &self))?;
                }
                Ok(out)
            }
        }
        d.deserialize_tuple(48, V)
    }
}
