#!/usr/bin/env bash
# Build the Arch package, as a normal user on Arch (makepkg refuses root):
#
#   contrib/arch/build.sh VERSION      # e.g. 0.2.0-beta.3
#
# writes target/packages/secret-vault-<VERSION>-x86_64.pkg.tar.zst.
# Install it with: sudo pacman -U target/packages/secret-vault-*.pkg.tar.zst
set -euo pipefail
cd "$(dirname "$0")"

ver=${1:?usage: build.sh VERSION}
# pacman versions have no "-": 0.2.0-beta.3 becomes 0.2.0beta.3, which
# vercmp sorts before 0.2.0, as a beta should.
export VAULT_PKGVER=${ver//-/}
export VAULT_VERSION=$ver

# The install hooks: the shared ones, called the way pacman calls them.
{
    echo "# Generated by contrib/arch/build.sh from contrib/linux/hooks.sh."
    cat ../linux/hooks.sh
    cat <<'HOOKS'
post_install() { vault_after_install /usr/bin/vault-setup-user 1; }
post_upgrade() { vault_after_install /usr/bin/vault-setup-user ""; }
pre_remove() { vault_before_remove /usr/bin/vault-setup-user; }
post_remove() { vault_after_remove; }
HOOKS
} >secret-vault.install

rm -rf pkg src
PKGDEST=$PWD/out makepkg --force --nodeps --noconfirm ${MAKEPKG_ARGS:-}
mkdir -p ../../target/packages
mv out/secret-vault-*.pkg.tar.zst "../../target/packages/secret-vault-$ver-x86_64.pkg.tar.zst"
rm -rf out pkg src secret-vault.install
ls -l ../../target/packages/secret-vault-*.pkg.tar.zst
